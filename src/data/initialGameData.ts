export function createInitialGameState(difficulty: Difficulty = 'normal'): GameState {
  const state: GameState = {
    turn: 1,
    phase: 'player',
    actionPoints: 3,
    maxActionPoints: 3,
    difficulty,
    regions: structuredClone(regions),
    factions: structuredClone(factions),
    officers: structuredClone(officers),
    logs: [
      {
        id: 'log_start',
        turn: 1,
        type: 'system',
        message: '暁ノ家の月評定が始まった。八州統一を目指そう。',
        createdAt: Date.now(),
      },
    ],
    lastBattleResult: null,
    selectedRegionId: 'r_akihara',
    selectedOfficerIds: ['o_harutsuna', 'o_sayo'],
    gameStatus: 'playing',
    rngSeed: nowSeed,
    settings: {
      sound: false,
      reducedMotion: false,
      showTutorial: true,
    },
    stats: {
      totalBattles: 0,
      recruitedOfficers: 0,
      defeatedFactions: [],
    },
    result: null,
  };

  if (difficulty === 'easy') {
    state.factions[PLAYER_FACTION_ID].gold += 120;
    state.factions[PLAYER_FACTION_ID].food += 180;
    state.factions[PLAYER_FACTION_ID].morale += 6;
    state.regions.r_akihara.localTroops += 100;
  }

  if (difficulty === 'hard') {
    state.factions[PLAYER_FACTION_ID].gold -= 70;
    state.factions[PLAYER_FACTION_ID].food -= 100;
    Object.values(state.factions)
      .filter((faction) => !faction.isPlayer && faction.isMajor)
      .forEach((faction) => {
        faction.gold += 80;
        faction.food += 120;
        faction.morale += 4;
      });
  }

  return state;
}
